// Internal service test only. No founder HTTP authentication is exposed.
import assert from 'node:assert/strict';
import { randomBytes, createHash } from 'node:crypto';
import { Secret, TOTP } from 'otpauth';
const url = new URL(process.env.DATABASE_URL ?? 'postgres://invalid/invalid');
if (process.env.NODE_ENV !== 'test' || !['localhost', '127.0.0.1'].includes(url.hostname) || url.pathname !== '/founders_auth_test') throw Error('Requires NODE_ENV=test and disposable localhost founders_auth_test DB');
const { db } = await import('../src/db/index.js');
const { migrateToLatest } = await import('../src/db/migrate.js');
const { bootstrapFounder, INITIAL_FOUNDER_EMAIL } = await import('../src/auth/founder-bootstrap.js');
const { founderPasswordStep, founderEnrollment, founderMfaStep, founderFirstPasswordRotation } = await import('../src/auth/founder-auth.js');
const { authorizeFounderInTransaction } = await import('../src/auth/founder-session.js');
const { resetFounderMfa } = await import('../src/auth/founder-mfa-reset.js');
const key = randomBytes(32);
const secret = randomBytes(32).toString('base64url');
const tempPassword = `Synthetic-${randomBytes(24).toString('base64url')}`;
const newPassword = `New-Synthetic-${randomBytes(24).toString('base64url')}`;
const now = new Date();
const later = new Date(now.getTime() + 60_000);
const code = (base32: string, at: Date) => new TOTP({ secret: Secret.fromBase32(base32), algorithm: 'SHA1', digits: 6, period: 30 }).generate({ timestamp: at.getTime() });
try {
  await migrateToLatest(() => {});
  assert.equal(await bootstrapFounder(db, { expectedSecretSha256: createHash('sha256').update(secret).digest('hex'), submittedSecret: secret, initialPassword: tempPassword, name: 'Synthetic owner' }), 'created');
  assert.equal(await founderPasswordStep(db, 'ordinary@example.test', tempPassword, now), null);
  assert.equal(await founderPasswordStep(db, INITIAL_FOUNDER_EMAIL, 'wrong-synthetic-password', now), null);
  const initial = await founderPasswordStep(db, INITIAL_FOUNDER_EMAIL, tempPassword, now);
  assert(initial && initial.stage === 'enroll');
  assert.equal(await db.transaction().execute((trx) => authorizeFounderInTransaction(trx, initial.token, 'founder.roles.manage', now)), null);
  assert.equal(await founderFirstPasswordRotation(db, initial.token, newPassword, now), null);
  const enrollment = await founderEnrollment(db, initial.token, key, now);
  assert(enrollment);
  assert.equal((await founderEnrollment(db, initial.token, key, now))?.secret, enrollment.secret);
  assert.equal(await founderMfaStep(db, initial.token, 'not-a-code', key, now), null);
  const verified = await founderMfaStep(db, initial.token, code(enrollment.secret, now), key, now);
  assert(verified && verified.kind === 'rotate' && verified.recoveryCodes?.length === 10);
  assert.equal(await founderMfaStep(db, initial.token, code(enrollment.secret, now), key, now), null);
  assert.equal(await db.transaction().execute((trx) => authorizeFounderInTransaction(trx, verified.flowToken, 'founder.roles.manage', now)), null);
  assert.equal(await founderFirstPasswordRotation(db, verified.flowToken, tempPassword, now), null);
  const session = await founderFirstPasswordRotation(db, verified.flowToken, newPassword, now);
  assert(session);
  assert.equal((await db.transaction().execute((trx) => authorizeFounderInTransaction(trx, session, 'founder.roles.manage', now)))?.role, 'owner');
  assert.equal(await founderFirstPasswordRotation(db, verified.flowToken, newPassword, now), null);
  assert.equal(await founderPasswordStep(db, INITIAL_FOUNDER_EMAIL, tempPassword, now), null);
  const login = await founderPasswordStep(db, INITIAL_FOUNDER_EMAIL, newPassword, later);
  assert(login && login.stage === 'verify');
  assert.equal(await founderMfaStep(db, login.token, code(enrollment.secret, now), key, now), null);
  const again = await founderMfaStep(db, login.token, code(enrollment.secret, later), key, later);
  assert(again && again.kind === 'session');
  const recoveryLogin = await founderPasswordStep(db, INITIAL_FOUNDER_EMAIL, newPassword, later);
  assert(recoveryLogin);
  const recovery = await founderMfaStep(db, recoveryLogin.token, verified.recoveryCodes[0], key, later);
  assert(recovery && recovery.kind === 'session');
  const reusedLogin = await founderPasswordStep(db, INITIAL_FOUNDER_EMAIL, newPassword, later);
  assert(reusedLogin);
  assert.equal(await founderMfaStep(db, reusedLogin.token, verified.recoveryCodes[0], key, later), null);
  const founder = await db.selectFrom('founder_accounts').selectAll().executeTakeFirstOrThrow();
  assert(!JSON.stringify(founder).includes(enrollment.secret));
  const audit = await db.selectFrom('founder_security_audit').selectAll().execute();
  for (const value of [secret, tempPassword, newPassword, enrollment.secret, session, ...verified.recoveryCodes]) assert(!JSON.stringify(audit).includes(value));
  await db.updateTable('founder_accounts').set({ status: 'suspended' }).where('id', '=', founder.id).execute();
  assert.equal(await db.transaction().execute((trx) => authorizeFounderInTransaction(trx, session, 'founder.roles.manage', later)), null);
  assert.equal(await founderPasswordStep(db, INITIAL_FOUNDER_EMAIL, newPassword, later), null);
  await db.updateTable('founder_accounts').set({ status: 'active' }).where('id', '=', founder.id).execute();
  const resetTime = new Date(now.getTime() + 120_000);
  assert.equal(await resetFounderMfa(db, session, 'wrong', code(enrollment.secret, resetTime), key, resetTime), false);
  assert.equal(await resetFounderMfa(db, session, newPassword, code(enrollment.secret, resetTime), key, resetTime), true);
  assert.equal(await db.transaction().execute((trx) => authorizeFounderInTransaction(trx, session, 'founder.roles.manage', resetTime)), null);
  assert.equal((await db.selectFrom('founder_recovery_codes').selectAll().where('founder_id', '=', founder.id).execute()).length, 0);
  const reenroll = await founderPasswordStep(db, INITIAL_FOUNDER_EMAIL, newPassword, resetTime);
  assert(reenroll && reenroll.stage === 'enroll');
  const newEnrollment = await founderEnrollment(db, reenroll.token, key, resetTime);
  assert(newEnrollment && newEnrollment.secret !== enrollment.secret);
  const newVerification = await founderMfaStep(db, reenroll.token, code(newEnrollment.secret, resetTime), key, resetTime);
  assert(newVerification && newVerification.kind === 'rotate' && newVerification.recoveryCodes?.length === 10);
  const rotatedAgain = `Rotated-Synthetic-${randomBytes(24).toString('base64url')}`;
  const newSession = await founderFirstPasswordRotation(db, newVerification.flowToken, rotatedAgain, resetTime);
  assert(newSession);
  assert.equal((await db.transaction().execute((trx) => authorizeFounderInTransaction(trx, newSession, 'founder.roles.manage', resetTime)))?.role, 'owner');
  assert.equal(await db.transaction().execute((trx) => authorizeFounderInTransaction(trx, session, 'founder.roles.manage', resetTime)), null);
  console.log('PASS internal founder flow: restricted password step, MFA, password rotation, recovery-code use and self-reset revocation with re-enrollment');
} finally { await db.destroy(); }
